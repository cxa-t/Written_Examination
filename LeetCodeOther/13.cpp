class Solution // 定义题解类，使用哈希表和贪心思想将罗马数字转换为整数
{
public: // 公有成员区域
    int romanToInt(string s) // 将字符串形式的罗马数字转换为对应的整数并返回
    {
        // 定义哈希表，存储每个罗马数字字符与对应整数之间的映射关系
        unordered_map<char, int> hash = {
            {'I', 1}, // 罗马数字 I 对应整数1
            {'V', 5}, // 罗马数字 V 对应整数5
            {'X', 10}, // 罗马数字 X 对应整数10
            {'L', 50}, // 罗马数字 L 对应整数50
            {'C', 100}, // 罗马数字 C 对应整数100
            {'D', 500}, // 罗马数字 D 对应整数500
            {'M', 1000}, // 罗马数字 M 对应整数1000
        }; // 哈希表初始化完成，可以通过字符快速查找对应的整数值
        int ret = 0; // 定义变量ret，用来记录当前已经计算出的罗马数字对应的整数总和
        for(int i = 0; i + 1 < s.size(); i++) // 从左向右遍历罗马数字，直到倒数第二个字符，因为每次都需要比较当前字符和后一个字符
        {
            int x = hash[s[i]]; // 获取当前罗马数字字符对应的整数值，例如当前字符是'I'，则x等于1
            int y = hash[s[i + 1]]; // 获取下一个罗马数字字符对应的整数值，用来判断当前字符应该加上还是减去
            ret += x >= y ? x : -x; // 如果当前数字大于等于后一个数字，说明当前数字正常相加；如果当前数字小于后一个数字，说明采用了罗马数字的减法规则，需要减去当前数字
        }
        return ret + hash[s.back()]; // 循环只处理到倒数第二个字符，最后一个字符还没有计算，因此将最后一个字符对应的整数加到ret中并返回结果
    }
};