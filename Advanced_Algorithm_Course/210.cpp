// https://leetcode.cn/problems/course-schedule-ii/


class Solution // 定义题解类，使用 BFS 拓扑排序求出完成所有课程的一种合法学习顺序
{
public: // 公有成员区域
    vector<int> findOrder(int n, vector<vector<int>>& prerequisites) // 返回完成全部 n 门课程的一种合法学习顺序，如果存在循环依赖导致无法完成所有课程，则返回空数组
    {
        unordered_map<int, vector<int>> edges; // 定义邻接表存储有向图，edges[b] 保存所有以课程 b 为前置课程的后续课程
        vector<int> in(n); // 定义入度数组，in[i] 表示课程 i 还有多少门前置课程需要完成，初始值全部为0
        for(auto e : prerequisites) // 遍历所有课程的先修关系，建立有向图并统计每门课程的入度
        {
            int a = e[0]; // 获取当前需要学习的课程 a
            int b = e[1]; // 获取课程 a 的前置课程 b，表示必须先学习课程 b 才能学习课程 a
            edges[b].push_back(a); // 建立一条从 b 指向 a 的有向边，表示课程 a 依赖课程 b
            in[a]++; // 课程 a 增加了一门前置课程，因此将课程 a 的入度加1
        }
        queue<int> q; // 定义 BFS 队列，用来保存当前入度为0、可以直接学习的课程
        for(int i = 0; i < n; i++) // 遍历所有课程，寻找没有前置课程的节点作为拓扑排序的起点
        {
            if(in[i] == 0) // 如果当前课程的入度为0，说明它没有尚未完成的前置课程，可以直接学习
                q.push(i); // 将当前课程加入队列，等待后续按照拓扑顺序进行处理
        }
        vector<int> ret; // 定义结果数组，用来记录课程的学习顺序，也就是拓扑排序的结果
        while(!q.empty()) // 只要队列不为空，说明还有可以继续学习的课程
        {
            int t = q.front(); // 取出队头课程 t，表示当前可以学习这门课程
            q.pop(); // 将课程 t 从队列中删除，表示当前课程已经被处理
            ret.push_back(t); // 将当前课程 t 加入结果数组，记录它在最终学习顺序中的位置
            for(int e : edges[t]) // 遍历所有依赖课程 t 的后续课程，即所有从 t 出发的有向边所指向的节点
            {
                in[e]--; // 当前课程 t 已经完成，因此后续课程 e 少了一门需要学习的前置课程，将其入度减1
                if(in[e] == 0) q.push(e); // 如果课程 e 的入度减为0，说明它的所有前置课程都已经完成，可以加入队列等待学习
            }
        }
        for(int i = 0; i < n; i++) // 拓扑排序结束后，遍历所有课程，检查是否还有课程存在未消除的前置依赖
        {
            if(in[i]) return {}; // 如果某门课程的入度仍然不为0，说明图中存在环形依赖，无法完成所有课程，因此返回空数组
        }
        return ret; // 如果所有课程的入度都变为0，说明全部课程都可以完成，返回记录好的合法拓扑排序结果
    }
};