// https://leetcode.cn/problems/01-matrix/


class Solution // 定义题解类，使用多源 BFS 计算矩阵中每个位置到最近的0的最短距离
{
public: // 公有成员区域
    vector<vector<int>> updateMatrix(vector<vector<int>>& mat) // 返回距离矩阵，ret[i][j]表示位置(i,j)到最近的0的最短距离
    {
        int m = mat.size(); // 获取矩阵的行数
        int n = mat[0].size(); // 获取矩阵的列数
        vector<vector<int>> ret(m, vector<int>(n, -1)); // 创建m行n列的结果矩阵，初始值全部设为-1，表示当前位置还没有被访问，距离尚未确定
        queue<pair<int, int>> q; // 定义 BFS 队列，每个元素保存一个位置的行下标和列下标，用于逐层向四周搜索
        for(int i = 0; i < m; i++) // 遍历矩阵中的每一行
        {
            for(int j = 0; j < n; j++) // 遍历当前行中的每一列
            {
                if(mat[i][j] == 0) // 如果当前位置的元素为0，说明它到最近的0的距离就是0
                {
                    q.push({i, j}); // 将所有值为0的位置加入 BFS 队列，作为多个搜索起点，这就是多源 BFS
                    ret[i][j] = 0; // 将当前位置的最短距离设置为0，同时表示该位置已经被访问
                }
            }
        }
        int dx[4] = {0, 0, 1, -1}; // 定义四个方向的行偏移量，分别对应左、右、下、上
        int dy[4] = {-1, 1, 0, 0}; // 定义四个方向的列偏移量，与dx配合实现向左、右、下、上移动
        while(q.size()) // 只要队列不为空，说明还有可以继续向四周扩展的位置
        {
            auto [a, b] = q.front(); // 取出队头元素，通过结构化绑定获取当前位置的行下标a和列下标b
            q.pop(); // 将当前已经取出的位置从队列中删除，避免重复处理
            for(int i = 0; i < 4; i++) // 枚举当前位置的四个相邻方向，尝试向左、右、下、上移动
            {
                int x = a + dx[i]; // 根据当前方向的行偏移量，计算相邻位置的行下标
                int y = b + dy[i]; // 根据当前方向的列偏移量，计算相邻位置的列下标
                if(x >= 0 && x < m && y >= 0 && y < n && ret[x][y] == -1) // 判断新位置是否没有越界，并且距离仍为-1，说明该位置之前没有被访问过
                {
                    q.push({x, y}); // 将这个合法且未访问过的位置加入队列，等待后续继续从它向四周扩展
                    ret[x][y] = ret[a][b] + 1; // 相邻位置到最近的0的距离等于当前位置的最短距离加1，由于BFS按照距离从近到远搜索，因此第一次访问时得到的就是最短距离
                }
            }
        }
        return ret; // 返回最终的距离矩阵，其中每个位置都记录了到最近的0的最短距离
    }
};