// https://leetcode.cn/problems/map-of-highest-peak/


class Solution // 定义题解类，使用多源 BFS 计算每个陆地位置到最近水域的最短距离，并将其作为该位置的高度
{
public: // 公有成员区域
    vector<vector<int>> highestPeak(vector<vector<int>>& isWater) // 返回满足条件的高度矩阵，要求水域高度为0，相邻位置高度差不超过1，并使最大高度尽可能大
    {
        int m = isWater.size(); // 获取矩阵的行数
        int n = isWater[0].size(); // 获取矩阵的列数
        vector<vector<int>> ret(m, vector<int>(n, -1)); // 创建m行n列的高度矩阵，初始全部设为-1，表示当前位置还没有被访问，高度尚未确定
        queue<pair<int, int>> q; // 定义 BFS 队列，每个元素保存一个位置的行下标和列下标，用于从水域向四周逐层扩展
        for(int i = 0; i < m; i++) // 遍历矩阵中的每一行，寻找所有水域位置
        {
            for(int j = 0; j < n; j++) // 遍历当前行中的每一列，判断当前位置是否为水域
            {
                if(isWater[i][j] == 1) // 如果当前位置的值为1，说明该位置是水域，按照题意高度必须为0
                {
                    q.push({i, j}); // 将当前水域位置加入 BFS 队列，使所有水域同时作为搜索起点，这就是多源 BFS
                    ret[i][j] = 0; // 将当前水域的高度设置为0，同时表示该位置已经被访问
                }
            }
        }
        int dx[4] = {0, 0, -1, 1}; // 定义四个方向的行偏移量，分别对应左、右、上、下
        int dy[4] = {-1, 1, 0, 0}; // 定义四个方向的列偏移量，与dx配合实现向左、右、上、下移动
        while(q.size()) // 只要队列不为空，说明还有已经确定高度的位置可以继续向四周扩展
        {
            auto [a, b] = q.front(); // 取出队头位置，通过结构化绑定获取当前位置的行下标a和列下标b
            q.pop(); // 将当前已经取出的位置从队列中删除，准备搜索它周围的四个相邻位置
            for(int i = 0; i < 4; i++) // 枚举当前位置的四个方向，尝试向左、右、上、下扩展
            {
                int x = a + dx[i]; // 根据当前方向的行偏移量，计算相邻位置的行下标
                int y = b + dy[i]; // 根据当前方向的列偏移量，计算相邻位置的列下标
                if(x >= 0 && x < m && y >= 0 && y < n && ret[x][y] == -1) // 判断新位置是否没有越界，并且高度仍为-1，说明该位置之前没有被访问过
                {
                    q.push({x, y}); // 将当前合法且未访问的位置加入队列，等待后续继续从它向四周扩展
                    ret[x][y] = ret[a][b] + 1; // 将相邻位置的高度设置为当前高度加1；由于BFS从所有水域同时向外逐层扩展，因此第一次访问时得到的就是到最近水域的最短距离
                }
            }
        }
        return ret; // 返回最终高度矩阵，每个位置的高度等于它到最近水域的最短距离，既满足相邻高度差不超过1，又能使最大高度尽可能大
    }
};