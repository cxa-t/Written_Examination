// https://leetcode.cn/problems/as-far-from-land-as-possible/


class Solution // 定义题解类，使用多源 BFS 计算所有海洋格子到最近陆地的最短距离，并返回其中的最大值
{
public: // 公有成员区域
    int maxDistance(vector<vector<int>>& grid) // 返回距离最近陆地最远的海洋格子的距离，如果网格中全是陆地或全是海洋，则返回-1
    {
        int m = grid.size(); // 获取网格的行数
        int n = grid[0].size(); // 获取网格的列数
        queue<pair<int, int>> q; // 定义 BFS 队列，每个元素保存一个格子的行下标和列下标，用于从所有陆地同时向四周扩展
        vector<vector<int>> ret(m, vector<int>(n, -1)); // 创建m行n列的距离矩阵，初始全部设为-1，表示当前位置还没有被访问，距离尚未确定
        for(int i = 0; i < m; i++) // 遍历网格中的每一行，寻找所有陆地格子
            for(int j = 0; j < n; j++) // 遍历当前行中的每一列，判断当前位置是否为陆地
                if(grid[i][j] == 1) // 如果当前位置的值为1，说明该位置是陆地，可以作为 BFS 的搜索起点
                    q.push({i,j}), ret[i][j] = 0; // 将当前陆地加入队列，并将它到最近陆地的距离设置为0，所有陆地共同作为多源 BFS 的起点
        int dx[4] = {0,0,-1,1}; // 定义四个方向的行偏移量，分别对应左、右、上、下
        int dy[4] = {-1,1,0,0}; // 定义四个方向的列偏移量，与dx配合实现向左、右、上、下移动
        int res = 0; // 记录所有海洋格子到最近陆地的最大距离，初始为0
        while(q.size()) // 只要队列不为空，说明还有可以继续向四周扩展的位置
        {
            auto [a, b] = q.front(); // 取出队头格子，通过结构化绑定获取当前位置的行下标a和列下标b
            q.pop(); // 将当前已经取出的位置从队列中删除，准备搜索它周围的四个相邻位置
            for(int i = 0; i < 4; i++) // 枚举当前位置的四个方向，尝试向左、右、上、下扩展
            {
                int x = a + dx[i]; // 根据当前方向的行偏移量，计算相邻位置的行下标
                int y = b + dy[i]; // 根据当前方向的列偏移量，计算相邻位置的列下标
                if(x >= 0 && x < m && y >= 0 && y < n && ret[x][y] == -1) // 判断新位置是否在网格范围内，并且距离仍为-1，说明该位置之前没有被访问过
                {
                    ret[x][y] = ret[a][b] + 1; // 将新位置到最近陆地的距离设置为当前位置的距离加1，由于多源 BFS 按距离从近到远搜索，因此第一次访问时得到的就是最短距离
                    res = max(res, ret[x][y]); // 比较当前海洋格子的最短距离和之前记录的最大距离，更新距离最近陆地最远的海洋格子的距离
                    q.push({x, y}); // 将当前合法且未访问过的位置加入队列，等待后续继续从它向四周扩展
                }
            }
        }
        return res == 0 ? -1 : res; // 如果res为0，说明不存在同时包含陆地和海洋的情况，返回-1；否则返回所有海洋格子到最近陆地的最大距离
    }
};