// https://leetcode.cn/problems/integer-replacement/

class Solution // 定义题解类
{
public: // 公有成员区域
    int integerReplacement(int n) // 返回把整数 n 变成 1 所需要的最少操作次数
    {
        int ret = 0; // 记录当前已经执行的操作次数
        while(n > 1) // 只要 n 还没有变成1，就继续进行操作
        {
            if(n % 2 == 0) // 如果 n 是偶数，根据题意只能执行 n /= 2
            {
                n /= 2; // 将当前偶数除以2，使 n 快速变小
                ret++; // 执行了一次操作，因此操作次数加1
            }
            else // 如果 n 是奇数，需要在 n+1 和 n-1 两种操作中选择更优的一种
            {
                if(n == 3) // 当 n 等于3时是特殊情况，3减1得到2再除以2只需要两步，比加1更优
                {
                    ret += 2; // 3 -> 2 -> 1，一共需要两次操作
                    n = 1; // 经过两次操作后直接变成1，结束循环
                }
                else if(n % 4 == 1) // 如果 n 除以4余1，说明 n-1 一定可以被4整除，此时优先执行 n-1
                {
                    ret += 2; // 实际过程是 n -> n-1 -> (n-1)/2，一共进行了两次操作
                    n /= 2; // 因为 n 是奇数且 n%4==1，(n-1)/2 与 n/2 的整数除法结果相同，所以直接写 n/=2
                }
                else // 此时 n 是奇数且 n%4==3，并且 n 不等于3，优先执行 n+1
                {
                    ret += 2; // 实际过程是 n -> n+1 -> (n+1)/2，一共进行了两次操作
                    n = n / 2 + 1; // 对奇数 n 来说，(n+1)/2 等于 n/2+1，因此直接计算下一状态
                }
            }
        }
        return ret; // 返回把 n 变成1所需要的最少操作次数
    }
};