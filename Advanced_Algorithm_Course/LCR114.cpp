//  https://leetcode.cn/problems/Jf1JuT/


class Solution {
    unordered_map<char, unordered_set<char>> edges; // 定义邻接表存储有向图，edges[a] 保存所有必须排在字符 a 后面的字符，unordered_set 用来避免重复建边
    unordered_map<char, int> in; // 定义入度哈希表，in[a] 表示字符 a 有多少个必须排在它前面的字符
    bool check = false; // 标记是否出现不符合字典序规则的单词关系，初始为 false，表示当前没有发现非法情况
public: // 公有成员区域
    string alienOrder(vector<string>& words)     {
        // 第一步：统计所有出现过的字符，并初始化每个字符的入度
        for(auto s : words) // 遍历单词数组中的每一个单词
            for(auto e : s) // 遍历当前单词中的每一个字符
                in[e] = 0; // 将当前字符加入入度哈希表，并将它的初始入度设置为0，保证所有出现过的字符都参与拓扑排序
        // 第二步：比较单词之间的字典序关系，建立字符之间的有向边
        int n = words.size(); // 获取单词数组的长度
        for(int i = 0; i < n; i++) // 枚举第一个单词，作为字典序中排在前面的单词
        {
            for(int j = i + 1; j < n; j++) // 枚举排在第一个单词后面的所有单词，建立两个单词之间的字母先后关系
            {
                add(words[i], words[j]); // 调用 add 函数，比较两个单词第一个不同的字符，并建立对应的有向边
                if(check) return ""; // 如果两个单词出现非法的前缀关系，说明不存在合法的字母顺序，直接返回空字符串
            }
        }
        // 第三步：将所有入度为0的字符加入队列，准备进行 BFS 拓扑排序
        queue<char> q; // 定义 BFS 队列，用于存储当前没有前驱字符、可以直接加入排序结果的字符
        for(auto [elem, count] : in) // 遍历入度哈希表，其中 elem 表示字符，count 表示该字符当前的入度
            if(count == 0) // 如果当前字符的入度为0，说明没有其他字符必须排在它前面
                q.push(elem); // 将当前字符加入队列，作为拓扑排序的起点之一
        string ret; // 定义结果字符串，用来保存最终得到的外星语言字母排列顺序
        // 第四步：使用 BFS 拓扑排序，依次处理入度为0的字符
        while(q.size()) // 只要队列不为空，说明还有可以继续处理的字符
        {
            char t = q.front(); // 取出队头字符 t，表示当前可以将这个字符加入最终排列
            q.pop(); // 将已经取出的字符从队列中删除，避免重复处理
            ret += t; // 将当前字符追加到结果字符串末尾，记录它在拓扑排序中的位置
            for(auto ch : edges[t]) // 遍历所有从字符 t 出发能够直接到达的字符，即所有必须排在 t 后面的字符
            {
                in[ch]--; // 当前字符 t 已经处理完成，因此后继字符 ch 少了一个需要排在它前面的字符，入度减1
                if(in[ch] == 0) // 如果后继字符 ch 的入度减为0，说明所有必须排在它前面的字符都已经处理完成
                    q.push(ch); // 将字符 ch 加入队列，等待后续处理
            }
        }
        // 第五步：检查是否存在环形依赖，判断拓扑排序是否成功
        for(auto [elem, count] : in) // 遍历所有字符及其最终入度，检查是否还有没有处理完成的字符
            if(count != 0) // 如果某个字符的入度仍然不为0，说明图中存在环形依赖，部分字符无法进入拓扑排序
                return ""; // 存在循环依赖，无法得到合法的字母排列顺序，返回空字符串
        return ret; // 如果所有字符的入度最终都变成0，说明不存在环形依赖，返回得到的合法字母顺序
    }
    void add(string& s1, string& s2) // 比较两个单词的字典序关系，根据第一个不同的字符建立有向边，并检查是否存在非法前缀关系
    {
        int n = min(s1.size(), s2.size()); // 获取两个单词长度的较小值，防止逐位比较时出现数组越界
        int i = 0; // 定义下标 i，用来从左到右寻找两个单词第一个不同的字符
        for(i = 0; i < n; i++) // 从第一个字符开始依次比较，最多比较较短单词的全部字符
        {
            if(s1[i] != s2[i]) // 如果当前位置的两个字符不相同，说明已经找到决定两个单词字典序的第一个不同字符
            {
                // 因为 s1 排在 s2 前面，所以 s1 中第一个不同的字符必须排在 s2 对应字符的前面
                char a = s1[i]; // 记录前一个单词中第一个不同的字符 a
                char b = s2[i]; // 记录后一个单词中对应位置的字符 b
                if(edges.count(a) == 0 || edges[a].count(b) == 0) // 如果 a 还没有对应的邻接表，或者 a 指向 b 的有向边尚不存在，则需要建立这条边
                {
                    edges[a].insert(b); // 在邻接表中建立 a -> b 的有向边，表示字符 a 必须排在字符 b 前面
                    in[b]++; // 由于字符 b 增加了一个必须排在它前面的字符 a，因此将 b 的入度加1
                }
                break; // 第一个不同字符已经能够确定两个单词的字典序关系，后面的字符不再影响这两个单词的先后顺序
            }
        }
        if(i == s2.size() && i < s1.size()) check = true; // 如果 s2 是 s1 的真前缀，但较长的 s1 反而排在较短的 s2 前面，说明字典序非法，将 check 设置为 true
    }
};