// https://leetcode.cn/problems/number-of-enclaves/


class Solution // 定义题解类，使用多源 BFS 统计无法通过陆地移动到网格边界的陆地单元格数量
{
public: // 公有成员区域
    int numEnclaves(vector<vector<int>>& grid) // 返回飞地的数量，即无法通过上下左右移动到达网格边界的陆地单元格总数
    {
        int m = grid.size(); // 获取网格的行数
        int n = grid[0].size(); // 获取网格的列数
        vector<vector<bool>> vis(m, vector<bool>(n, false)); // 创建m行n列的访问标记数组，初始全部为false，表示所有位置都没有被访问过
        queue<pair<int, int>> q; // 定义 BFS 队列，每个元素保存一个陆地位置的行下标和列下标
        for(int i = 0; i < m; i++) // 遍历网格中的每一行，寻找位于边界上的陆地
        {
            for(int j = 0; j < n; j++) // 遍历当前行中的每一列，判断当前位置是否属于网格边界
            {
                if(i == 0 || i == m - 1 || j == 0 || j == n - 1) // 如果当前位置位于第一行、最后一行、第一列或最后一列，说明它是边界位置
                {
                    if(grid[i][j] == 1) // 如果当前边界位置的值为1，说明这里是陆地，可以作为 BFS 的搜索起点
                    {
                        q.push({i, j}); // 将当前边界陆地加入队列，后续从这些位置同时向内部搜索，这就是多源 BFS
                        vis[i][j] = true; // 将当前边界陆地标记为已访问，表示它能够直接到达网格边界，不属于飞地
                    }
                }
            }
        }
        int dx[4] = {0, 0, -1, 1}; // 定义四个方向的行偏移量，分别对应左、右、上、下
        int dy[4] = {-1, 1, 0, 0}; // 定义四个方向的列偏移量，与dx配合实现向左、右、上、下移动
        while(q.size()) // 只要队列不为空，说明还有能够从边界到达的陆地需要继续搜索
        {
            auto [a, b] = q.front(); // 取出队头陆地位置，通过结构化绑定获取当前行下标a和列下标b
            q.pop(); // 将当前已经取出的位置从队列中删除，准备搜索它周围的四个方向
            for(int i = 0; i < 4; i++) // 枚举当前位置的四个相邻方向，寻找与边界陆地连通的其他陆地
            {
                int x = a + dx[i]; // 根据当前方向的行偏移量，计算相邻位置的行下标
                int y = b + dy[i]; // 根据当前方向的列偏移量，计算相邻位置的列下标
                if(x >= 0 && x < m && y >= 0 && y < n && !vis[x][y] && grid[x][y] == 1) // 判断新位置是否在网格范围内、是否没有访问过，并且必须是值为1的陆地
                {
                    vis[x][y] = true; // 将当前陆地标记为已访问，说明它可以通过其他陆地与网格边界连通，因此不属于飞地
                    q.push({x, y}); // 将当前合法陆地加入队列，后续继续从它向四周搜索，寻找更多与边界连通的陆地
                }
            }
        }
        int ret = 0; // 记录最终的飞地数量，也就是无法到达网格边界的陆地单元格数量
        for(int i = 0; i < m; i++) // 再次遍历网格中的每一行，统计没有被 BFS 访问过的陆地
        {
            for(int j = 0; j < n; j++) // 遍历当前行中的每一列，检查当前位置是否属于飞地
            {
                if(grid[i][j] == 1 && !vis[i][j]) // 如果当前位置是陆地，并且没有被从边界出发的 BFS 访问过，说明它无法通过陆地到达边界
                {
                    ret++; // 当前陆地属于飞地，因此飞地单元格数量加1
                }
            }
        }
        return ret; // 返回所有无法到达网格边界的陆地单元格总数
    }
};